#!/usr/bin/env python3
"""Career Sims brain tool.

  python3 career-sims/tools/brains.py build   # write YAML twins and catalog.json from the JSON brains
  python3 career-sims/tools/brains.py check   # validate everything (CI runs this on every push)

Checks: JSON Schema; YAML twin equals JSON; canon copy matches the pinned SHA-256;
every brain pins the same commit/hash as canon/PIN.json; directive IDs exist in the
official list; no directive wording is copied into a brain; simulation and
not-Roger identity rules present; catalog.json matches the files; retired or
non-current domains are never linked anywhere in the site.
"""
import hashlib, json, os, re, sys
import yaml
from jsonschema import Draft202012Validator

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BR = os.path.join(ROOT, "brains")
FORBIDDEN = [r"nextxus\.online", r"emergent", r"keywebco\.net"]

def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()

def brains():
    return sorted(f[:-5] for f in os.listdir(BR) if f.endswith(".json"))

def load(i):
    return json.load(open(os.path.join(BR, i + ".json"), encoding="utf-8"))

def build():
    cat = []
    for i in brains():
        b = load(i)
        with open(os.path.join(BR, i + ".yaml"), "w", encoding="utf-8") as f:
            f.write("# YAML twin of %s.json (generated by tools/brains.py build; same content).\n" % i)
            yaml.safe_dump(b, f, sort_keys=False, allow_unicode=True, width=1000)
        cat.append({"id": i, "name": b["name"], "career_title": b["career_title"], "safety_tier": b["safety_tier"],
                    "safety_domain": b.get("safety_domain"), "summary": b["backstory"].split(". ")[0].rstrip(".") + ".",
                    "greeting": b["greeting"], "scope": b["knowledge"]["scope"],
                    "json": "brains/%s.json" % i, "yaml": "brains/%s.yaml" % i,
                    "json_sha256": sha(os.path.join(BR, i + ".json")), "yaml_sha256": sha(os.path.join(BR, i + ".yaml"))})
    pin = json.load(open(os.path.join(ROOT, "canon", "PIN.json")))
    out = {"title": "Next-Xus Career Sims catalog", "schema": "nextxus.sim-brain/1", "generated_by": "tools/brains.py build",
           "canon": {k: pin[k] for k in ("directives_repo", "directives_path", "directives_commit", "directives_sha256", "directives_edition")},
           "count": len(cat), "sims": cat}
    with open(os.path.join(ROOT, "catalog.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2, ensure_ascii=False); f.write("\n")
    print("built", len(cat), "brains")

def check():
    errs = []
    schema = json.load(open(os.path.join(ROOT, "schema", "sim-brain.schema.json")))
    v = Draft202012Validator(schema)
    pin = json.load(open(os.path.join(ROOT, "canon", "PIN.json")))
    canon_path = os.path.join(ROOT, "canon", "sacred-directives.json")
    if sha(canon_path) != pin["directives_sha256"]:
        errs.append("canon/sacred-directives.json does not match the pinned SHA-256")
    canon = json.load(open(canon_path, encoding="utf-8"))
    ids = {d["id"] for d in canon["directives"]}
    if len(ids) != 73 or canon["gate"]["id"] != "DIR-000":
        errs.append("canon copy does not hold DIR-000 plus 73 directives")
    texts = [canon["gate"]["text"]] + [d["text"] for d in canon["directives"]]
    cat = json.load(open(os.path.join(ROOT, "catalog.json"), encoding="utf-8"))
    cat_ids = [s["id"] for s in cat["sims"]]
    if cat_ids != brains():
        errs.append("catalog.json ids %s do not match brain files %s" % (cat_ids, brains()))
    for i in brains():
        b = load(i)
        for e in v.iter_errors(b):
            errs.append("%s: schema: %s at %s" % (i, e.message, "/".join(map(str, e.path))))
        if b.get("id") != i:
            errs.append("%s: id does not match file name" % i)
        c = b.get("canon", {})
        for k in ("directives_commit", "directives_sha256"):
            if c.get(k) != pin[k]:
                errs.append("%s: canon.%s is not the pinned value" % (i, k))
        for d in c.get("emphasized_directives", []):
            if d not in ids:
                errs.append("%s: unknown directive id %s" % (i, d))
        blob = json.dumps(b, ensure_ascii=False)
        for t in texts:
            for frag in re.split(r"(?<=[.!?])\s+", t):
                if len(frag) > 40 and frag in blob:
                    errs.append("%s: copies directive wording (%s...)" % (i, frag[:30]))
        ir = b.get("identity_rules", "").lower()
        if "simulat" not in ir or "not roger sim" not in ir:
            errs.append("%s: identity_rules must say it is a simulation and not Roger Sim" % i)
        y = os.path.join(BR, i + ".yaml")
        if not os.path.exists(y) or yaml.safe_load(open(y, encoding="utf-8")) != b:
            errs.append("%s: YAML twin missing or different from JSON (run build)" % i)
        entry = next((s for s in cat["sims"] if s["id"] == i), None)
        if entry and (entry["json_sha256"] != sha(os.path.join(BR, i + ".json")) or (os.path.exists(y) and entry["yaml_sha256"] != sha(y))):
            errs.append("%s: catalog.json hash is stale (run build)" % i)
    for dp, _, fs in os.walk(ROOT):
        if os.sep + "canon" in dp:
            continue
        for f in fs:
            if f.endswith((".html", ".js", ".json", ".yaml", ".md", ".css")):
                body = open(os.path.join(dp, f), encoding="utf-8").read()
                for pat in FORBIDDEN:
                    if re.search(pat, body, re.I):
                        errs.append("%s: mentions a retired or non-current domain/host (%s)" % (os.path.relpath(os.path.join(dp, f), ROOT), pat))
    if errs:
        print("\n".join("FAIL " + e for e in errs)); sys.exit(1)
    print("OK: %d brains valid, canon pinned at %s" % (len(brains()), pin["directives_commit"][:7]))

if __name__ == "__main__":
    {"build": build, "check": check}[sys.argv[1] if len(sys.argv) > 1 else "check"]()
