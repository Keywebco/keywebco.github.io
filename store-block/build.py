"""Build the shared Next-Xus store block (EE-2026-11-20-005) from the brain's product list.

Gumroad is the truth for listings. This copies only title, link, and price from
Keywebco/nextxus-brain 04-builds/products.yaml (rows with status: live). It adds no tracking
and no checkout; every button goes to Gumroad.

Run:  python3 build.py [path/to/products.yaml]
      (no path: reads the public raw file from the brain on GitHub)
Writes: products.json, store-block.html, store-block.js (all in this folder). Needs PyYAML."""
import html, json, os, re, sys, urllib.request

import yaml

RAW = "https://raw.githubusercontent.com/Keywebco/nextxus-brain/main/04-builds/products.yaml"
HERE = os.path.dirname(os.path.abspath(__file__))


def load(src):
    if src:
        text = open(src, encoding="utf-8").read()
    else:
        with urllib.request.urlopen(RAW, timeout=30) as r:
            text = r.read().decode("utf-8")
    rows = yaml.safe_load(text) or []
    out = []
    for r in rows:
        if not isinstance(r, dict) or r.get("status") != "live":
            continue
        url = str(r.get("url", ""))
        if not re.fullmatch(r"https://keywebster\.gumroad\.com/l/[A-Za-z0-9]+", url):
            continue  # only exact Gumroad listing links
        price = str(r.get("price", "")).replace(" USD", "")
        price = re.sub(r"\.00$", "", price)
        out.append({"id": r.get("id"), "title": r["title"], "url": url, "price": price,
                    "topic": r.get("topic", ""), "verified": str(r.get("verified", ""))})
    return out


def snippet(items):
    lis = "\n".join('  <li><a href="%s" rel="noopener">%s</a> <span class="nx-store-price">%s</span></li>'
                    % (html.escape(i["url"], quote=True), html.escape(i["title"], quote=False), html.escape(i["price"]))
                    for i in items)
    return ("<!-- nx-store-block:start (generated by store-block/build.py from nextxus-brain 04-builds/products.yaml; do not hand-edit) -->\n"
            '<section class="nx-store-block" aria-label="Books and guides by Roger Keyserling on Gumroad">\n'
            "<h2>Books and guides on Gumroad</h2>\n"
            "<p>Gumroad is the store. These links go straight there. No tracking, no checkout on this site.</p>\n"
            "<ul>\n" + lis + "\n</ul>\n</section>\n<!-- nx-store-block:end -->\n")


JS = """/* Next-Xus shared store block (EE-2026-11-20-005). Generated by store-block/build.py. Do not hand-edit.
   Use on any Federation page:
     <div data-nx-store></div>
     <script src="https://next-xus.net/store-block/store-block.js" defer></script>
   Optional: data-nx-store="5" shows only the first 5 items, with a link to the full store.
   No tracking, no cookies, no network calls: the list is inside this file. Buttons go to Gumroad. */
(function () {
  var ITEMS = __ITEMS__;
  function render(el) {
    var n = parseInt(el.getAttribute('data-nx-store'), 10);
    var list = (n > 0) ? ITEMS.slice(0, n) : ITEMS;
    var sec = document.createElement('section');
    sec.className = 'nx-store-block';
    sec.setAttribute('aria-label', 'Books and guides by Roger Keyserling on Gumroad');
    var h = document.createElement('h2'); h.textContent = 'Books and guides on Gumroad'; sec.appendChild(h);
    var p = document.createElement('p');
    p.textContent = 'Gumroad is the store. These links go straight there. No tracking, no checkout on this site.';
    sec.appendChild(p);
    var ul = document.createElement('ul');
    list.forEach(function (i) {
      var li = document.createElement('li');
      var a = document.createElement('a'); a.href = i.url; a.rel = 'noopener'; a.textContent = i.title;
      var s = document.createElement('span'); s.className = 'nx-store-price'; s.textContent = ' ' + i.price;
      li.appendChild(a); li.appendChild(s); ul.appendChild(li);
    });
    sec.appendChild(ul);
    if (list.length < ITEMS.length) {
      var more = document.createElement('p'); var m = document.createElement('a');
      m.href = 'https://next-xus.net/store.html'; m.textContent = 'See all ' + ITEMS.length + ' books and guides';
      more.appendChild(m); sec.appendChild(more);
    }
    el.innerHTML = ''; el.appendChild(sec);
  }
  function go() { document.querySelectorAll('[data-nx-store]').forEach(render); }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', go); else go();
})();
"""


def main():
    items = load(sys.argv[1] if len(sys.argv) > 1 else None)
    if not items:
        sys.exit("REFUSED: no live products found; nothing written")
    json.dump({"source": "Keywebco/nextxus-brain 04-builds/products.yaml (Gumroad is the truth)",
               "count": len(items), "items": items},
              open(os.path.join(HERE, "products.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    open(os.path.join(HERE, "store-block.html"), "w", encoding="utf-8").write(snippet(items))
    open(os.path.join(HERE, "store-block.js"), "w", encoding="utf-8").write(
        JS.replace("__ITEMS__", json.dumps([{k: i[k] for k in ("title", "url", "price")} for i in items], ensure_ascii=False)
                   .replace("</", "<\\/")))
    print("Wrote %d products." % len(items))


if __name__ == "__main__":
    main()
